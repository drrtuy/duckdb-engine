uint32_t EventLength(const char *p)
{
  const auto *b= reinterpret_cast<const unsigned char *>(p);
  return uint32_t(b[0]) | uint32_t(b[1]) << 8 | uint32_t(b[2]) << 16 |
         uint32_t(b[3]) << 24;
}

std::vector<std::string> Events(const std::string &payload)
{
  std::vector<std::string> result;
  size_t offset= 0;
  while (offset < payload.size())
  {
    if (payload.size() - offset < 19)
      throw std::runtime_error("CDC: truncated event header");
    auto size= EventLength(payload.data() + offset + 9);
    if (size < 19 || size > payload.size() - offset)
      throw std::runtime_error("CDC: invalid event size");
    result.emplace_back(payload.substr(offset, size));
    offset+= size;
  }
  return result;
}

std::string FormatKey(const std::string &format)
{
  if (format.size() < 24 || static_cast<unsigned char>(format[4]) != 15)
    throw std::runtime_error("CDC: missing format description");
  bool checksum= static_cast<unsigned char>(format[format.size() - 5]) == 1;
  return format.substr(19, format.size() - 19 - (checksum ? 4 : 0));
}

std::string Base64(const std::string &bytes)
{
  static const char alphabet[]= "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  std::string result;
  result.reserve((bytes.size() + 2) / 3 * 4);
  for (size_t i= 0; i < bytes.size(); i+= 3)
  {
    const auto a= static_cast<unsigned char>(bytes[i]);
    const auto b= i + 1 < bytes.size() ? static_cast<unsigned char>(bytes[i + 1]) : 0;
    const auto c= i + 2 < bytes.size() ? static_cast<unsigned char>(bytes[i + 2]) : 0;
    result+= alphabet[a >> 2];
    result+= alphabet[(a & 3) << 4 | b >> 4];
    result+= i + 1 < bytes.size() ? alphabet[(b & 15) << 2 | c >> 6] : '=';
    result+= i + 2 < bytes.size() ? alphabet[c & 63] : '=';
  }
  return result;
}

static std::string Upper(std::string s)
{
  while (!s.empty() && std::isspace(static_cast<unsigned char>(s.back())))
    s.pop_back();
  size_t start= 0;
  while (start < s.size() && std::isspace(static_cast<unsigned char>(s[start])))
    ++start;
  s.erase(0, start);
  for (char &c : s)
    c= std::toupper(static_cast<unsigned char>(c));
  return s;
}

Effects DecodeEffects(const std::string &payload, const std::string &database)
{
  Effects result;
  std::string statement;
  bool checksum= false;
  bool map_seen= false;
  for (const auto &event : Events(payload))
  {
    unsigned type= static_cast<unsigned char>(event[4]);
    if (type == 15)
    {
      if (!result.format.empty() || event.size() < 24)
        throw std::runtime_error("CDC: invalid format context");
      result.format= event;
      checksum= static_cast<unsigned char>(event[event.size() - 5]) == 1;
      continue;
    }
    if (result.format.empty())
      throw std::runtime_error("CDC: no format context");
    size_t end= event.size() - (checksum ? 4 : 0);
    if (end < 19)
      throw std::runtime_error("CDC: invalid checksum trailer");
    if (type == 162)
    {
      if (end < 32 || (static_cast<unsigned char>(event[31]) & 0xc0))
        throw std::runtime_error("CDC: XA or malformed GTID is unsupported");
      continue;
    }
    if (type == 5 || type == 13 || type == 14 || type == 16 ||
        type == 28 || type == 29 || type == 160)
      continue;
    if (type == 2)
    {
      if (end < 32)
        throw std::runtime_error("CDC: truncated query event");
      const auto *p= reinterpret_cast<const unsigned char *>(event.data());
      size_t db_length= p[27];
      size_t status_length= p[30] | size_t(p[31]) << 8;
      size_t db_offset= 32 + status_length;
      if (db_offset > end || db_length + 1 > end - db_offset ||
          event[db_offset + db_length] != 0)
        throw std::runtime_error("CDC: invalid query database");
      QueryEvent query{event.substr(db_offset, db_length),
                       event.substr(db_offset + db_length + 1, end - db_offset - db_length - 1)};
      auto upper= Upper(query.query);
      const std::string marker= "/* GENERATED BY SERVER */";
      if (upper.rfind("DROP TABLE ", 0) == 0 && upper.size() >= marker.size() &&
          upper.compare(upper.size() - marker.size(), marker.size(), marker) == 0)
      {
        auto end= query.query.find_last_not_of(" \t\r\n");
        query.query.erase(end + 1 - marker.size());
        upper= Upper(query.query);
      }
      if (upper == "BEGIN")
        continue;
      if (upper == "COMMIT")
      {
        result.transaction_end= true;
        continue;
      }
      if (upper == "ROLLBACK")
      {
        result.transaction_end= true;
        result.rollback= true;
        continue;
      }
      if (!result.ddl.query.empty() || !statement.empty() || !result.statements.empty())
        throw std::runtime_error("CDC: mixed query/row transaction is unsupported");
      result.ddl= std::move(query);
      continue;
    }
    if (type == 19)
    {
      if (!result.ddl.query.empty() || end < 29)
        throw std::runtime_error("CDC: invalid table map");
      size_t length= static_cast<unsigned char>(event[27]);
      if (length + 29 > end || event.substr(28, length) != database)
        throw std::runtime_error("CDC: table map outside the configured database");
      size_t table_offset= 29 + length;
      if (table_offset >= end || event[28 + length] != 0)
        throw std::runtime_error("CDC: invalid table map database");
      size_t table_length= static_cast<unsigned char>(event[table_offset]);
      if (table_offset + table_length + 2 > end || table_length == 0 ||
          event[table_offset + table_length + 1] != 0)
        throw std::runtime_error("CDC: invalid table name");
      result.tables.push_back(event.substr(table_offset + 1, table_length));
      statement+= event;
      map_seen= true;
      continue;
    }
    if ((type >= 23 && type <= 25) || (type >= 30 && type <= 32))
    {
      if (!map_seen || end < 27 || !result.ddl.query.empty())
        throw std::runtime_error("CDC: row event without table map");
      statement+= event;
      if (static_cast<unsigned char>(event[25]) & 1)
      {
        result.statements.push_back(std::move(statement));
        statement.clear();
        map_seen= false;
      }
      continue;
    }
    throw std::runtime_error("CDC: unsupported event type " + std::to_string(type));
  }
  if (result.format.empty() || !statement.empty())
    throw std::runtime_error("CDC: incomplete transaction payload");
  if (result.rollback)
    result.statements.clear();
  return result;
}

