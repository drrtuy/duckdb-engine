#include "events.h"
#include "ddl.h"

#include <functional>
#include <stdexcept>
#include <string>

using namespace myduck::cdc;

static void Need(bool ok)
{
  if (!ok) throw std::runtime_error("CDC event test failed");
}

static void Reject(const std::function<void()> &f)
{
  try { f(); } catch (const std::runtime_error &) { return; }
  throw std::runtime_error("CDC event test expected rejection");
}

static std::string Event(unsigned type, const std::string &body)
{
  std::string result(19, 0);
  result[4]= type;
  result+= body;
  result.append(4, 0);
  unsigned length= result.size();
  for (unsigned i= 0; i < 4; ++i) result[9 + i]= (length >> (8 * i)) & 255;
  return result;
}

static std::string Query(const std::string &sql)
{
  std::string body(13, 0);
  body[8]= 2;
  body+= "db";
  body+= '\0';
  body+= sql;
  return Event(2, body);
}

int main()
{
  Need(Base64("") == "");
  Need(Base64("f") == "Zg==");
  Need(Base64("fo") == "Zm8=");
  Need(Base64("foo") == "Zm9v");
  auto format= Event(15, std::string(1, 1));
  Need(!FormatKey(format).empty());
  Need(!DecodeEffects(format + Query("BEGIN"), "db").transaction_end);
  Need(DecodeEffects(format + Query("COMMIT"), "db").transaction_end);
  Need(DecodeEffects(format + Query("ROLLBACK"), "db").transaction_end);
  Need(DecodeEffects(format + Event(28, "") + Event(5, "") +
                     Event(13, "") + Event(14, ""), "db").statements.empty());
  auto ddl= DecodeEffects(format + Query("DROP TABLE db.t /* generated by server */"), "db");
  Need(PlanDdl(ddl.ddl.query, ddl.ddl.database, "db").operation == "DROP");
  Reject([&] { DecodeEffects(Query("BEGIN"), "db"); });
  Reject([&] { DecodeEffects(format + Event(200, ""), "db"); });
  Reject([&] { DecodeEffects(format + Query("DROP TABLE t") + Query("DROP TABLE u"), "db"); });
  std::string map(8, 0);
  map+= char(2);
  map+= "db";
  map+= '\0';
  map+= char(1);
  map+= 't';
  map+= '\0';
  auto table= Event(19, map);
  std::string row(8, 0);
  row[6]= 1;
  auto data= Event(24, row);
  auto effects= DecodeEffects(format + table + data, "db");
  Need(effects.statements.size() == 1 && effects.tables == std::vector<std::string>{"t"});
  Reject([&] { DecodeEffects(format + table + data, "other"); });
  Reject([&] { DecodeEffects(format + data, "db"); });
  Reject([&] { DecodeEffects(format + table, "db"); });
  Need(DecodeEffects(format + table + data + Query("ROLLBACK"), "db").statements.empty());
  auto stream= format + table + data;
  for (size_t i= 1; i < stream.size(); ++i)
  {
    if (i != format.size() && i != format.size() + table.size())
      Reject([&] { Events(stream.substr(0, i)); });
  }
  auto malformed= stream;
  malformed[9]= 0;
  Reject([&] { Events(malformed); });
  auto badquery= Query("BEGIN");
  badquery[34]= 'x';
  Reject([&] { DecodeEffects(format + badquery, "db"); });
}
